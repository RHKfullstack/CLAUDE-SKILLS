const files = {
  "AGENTS.md": agents,
  "CLAUDE.md": claude,
  "copilot-instructions.md": copilot,
  "cursor-skills.mdc": cursor,
};

let stale = 0;
if (!checkOnly) mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const target = join(outDir, name);
  if (checkOnly) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current !== content) {
      console.error(`stale: adapters/${name}`);
      stale++;
    }
    continue;
  }
  writeFileSync(target, content, "utf8");
  console.log(`wrote adapters/${name}`);
}

if (checkOnly) {
  if (stale > 0) {
    console.error(`\n${stale} adapter(s) out of date — run: node scripts/build-adapters.mjs`);
    process.exit(1);
  }
  console.log(`adapters are current (${skills.length} skills)`);
} else {
  console.log(`\n${skills.length} skills indexed`);
}
