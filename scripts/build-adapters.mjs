#!/usr/bin/env node
/**
 * Regenerate the cross-tool adapters from the canonical skills.
 *
 * Source of truth: skills/<name>/SKILL.md (YAML frontmatter: name, description).
 * Outputs:        adapters/AGENTS.md, adapters/CLAUDE.md,
 *                 adapters/copilot-instructions.md, adapters/cursor-skills.mdc
 *
 * Usage:
 *   node scripts/build-adapters.mjs           # write the adapters
 *   node scripts/build-adapters.mjs --check   # exit 1 if any adapter is stale
 *
 * No dependencies. The adapters are indexes, not copies: they point at the
 * canonical SKILL.md so there is exactly one place to edit a skill.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, "skills");
const outDir = join(root, "adapters");
const checkOnly = process.argv.includes("--check");

/** Parse `name` and `description` out of a leading YAML frontmatter block. */
function frontmatter(raw) {
  // Windows editors happily prepend a UTF-8 BOM; YAML frontmatter must start at byte 0.
  const text = raw.replace(/^\uFEFF/, "");
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return null;
  const out = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].trim();
  }
  return out.name && out.description ? out : null;
}

function collect() {
  if (!existsSync(skillsDir)) {
    console.error(`skills directory not found: ${skillsDir}`);
    process.exit(2);
  }
  const skills = [];
  for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const file = join(skillsDir, entry.name, "SKILL.md");
    if (!existsSync(file)) continue;
    const fm = frontmatter(readFileSync(file, "utf8"));
    if (!fm) {
      console.error(`invalid frontmatter: skills/${entry.name}/SKILL.md`);
      process.exit(2);
    }
    if (fm.name !== entry.name) {
      console.error(`name/directory mismatch: skills/${entry.name}/SKILL.md declares "${fm.name}"`);
      process.exit(2);
    }
    skills.push({ dir: entry.name, ...fm });
  }
  skills.sort((a, b) => a.dir.localeCompare(b.dir));
  return skills;
}

const skills = collect();

const FAMILY = (dir) => {
  if (dir === "ui-design" || dir === "creative-designer" || dir === "senior-frontend-engineering") return "Design";
  if (dir === "stack-php-mysql") return "Stack";
  return "Engineering";
};

function table() {
  const rows = skills.map((s) => `| \`${s.dir}\` | ${FAMILY(s.dir)} | ${s.description} |`);
  return ["| Skill | Family | Use when |", "|---|---|---|", ...rows].join("\n");
}

